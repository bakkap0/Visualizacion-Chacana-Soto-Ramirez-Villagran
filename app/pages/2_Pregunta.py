from shared import st, eda, setup, controls, chart, require_values, comparison

setup('Patrones y análisis de la pregunta')
df, variable = controls()
require_values(df, variable)
st.subheader('Evolución temporal')
minimum = st.slider('Mínimo de horas para mostrar una media diaria exploratoria', min_value=1,max_value=24,value=18)
chart(eda.daily_chart(df,variable,minimum),'daily')
st.caption('Las líneas se interrumpen cuando el día no alcanza el mínimo seleccionado. Este control cambia la cobertura del resumen, no las mediciones. El criterio es exploratorio, sin equivalencia normativa.')
st.subheader('Hora del día y época del año')
common = comparison(df, variable)
profile = eda.hourly_profile(common,variable)
chart(eda.hourly_chart(common,variable),'hourly')
peaks = profile.dropna(subset=['mediana']).sort_values('mediana',ascending=False).groupby('estacion',observed=True).head(1)
st.write('El horario del máximo mediano cambia entre estaciones. Para esta selección:')
st.dataframe(peaks[['estacion','hora','mediana','n']],hide_index=True)
st.caption('Se muestran perfiles con al menos 24 observaciones por estación/hora. Si varias horas empatan, la tabla muestra una de ellas. El patrón horario mezcla años y épocas; no identifica por sí solo una fuente emisora.')
station = st.selectbox('Estación para el mapa de mes y hora', sorted(df.estacion.unique()))
chart(eda.month_hour_chart(df,variable,station),'month_hour')
st.caption('Cada celda es la mediana de las horas observadas de ese mes calendario, agrupando los años seleccionados. Se ocultan celdas con menos de 12 observaciones. El gráfico muestra patrones descriptivos, sin demostrar estacionalidad estable.')
st.subheader('Relaciones con meteorología')
predictor = st.selectbox('Variable meteorológica',list(eda.METEOROLOGY),format_func=lambda v:eda.METEOROLOGY[v][0])
rel = eda.relationships(df,variable,predictor)
if rel.n_pares.sum() == 0:
    st.warning('No hay pares para esta selección. Temperatura y humedad solo están disponibles en Concón.')
else:
    chart(eda.scatter_chart(df,variable,predictor),'scatter')
    st.dataframe(rel.round(3),hide_index=True)
    st.caption('El gráfico muestra una muestra reproducible de hasta 1.500 pares por estación. Spearman usa todos los pares disponibles de cada estación. Una asociación puede variar según horario o época del año; no implica causalidad.')
st.subheader('Conclusiones preliminares')
st.write('Las diferencias entre estaciones deben interpretarse junto a su cobertura. Los perfiles horarios y la relación con el viento pueden cambiar según estación y contaminante. Usa los filtros para comprobar si los patrones se mantienen al cambiar el periodo.')
st.write('La validación pendiente limita las conclusiones. No se calculan incumplimientos oficiales, no se atribuyen concentraciones a empresas y no se evalúa un efecto causal de la nueva red pública.')
